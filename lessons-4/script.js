//Дано ціле число. З'ясувати, чи воно простим (простим називається число, більше ніж 1, які мають інших дільників крім 1 і себе)
let namNum = 7;
let isPrime = true;
if (namNum <= 1) {
  isPrime = false;
}
for (let b = 2; b < namNum; b++) {
  if (namNum % b === 0) {
    isPrime = false;
    break;
  }
}
if (isPrime === true) {
  console.log("Число просте");
} else {
  console.log("Число не просте");
}

